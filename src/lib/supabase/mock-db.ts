  // Helper methods
  public addApplication(app: Omit<AdmissionApplication, "id" | "application_reference" | "status" | "created_at">): AdmissionApplication {
    const refNum = `AAC-2026-ADM${1000 + this.admissionApplications.length + 1}`;
    const newApp: AdmissionApplication = {
      ...app,
      id: `adm-app-${Date.now()}`,
      application_reference: refNum,
      status: "pending",
      created_at: new Date().toISOString(),
    };
    this.admissionApplications.unshift(newApp);
    return newApp;
  }

  public updateApplicationStatus(id: string, status: AdmissionApplication["status"], notes?: string): AdmissionApplication | null {
    const app = this.admissionApplications.find((a) => a.id === id || a.application_reference === id);
    if (!app) return null;
    app.status = status;
    if (notes) app.review_notes = notes;
    app.reviewed_at = new Date().toISOString();
    return app;
  }

  public getApplicationByRef(ref: string): AdmissionApplication | undefined {
    const cleanRef = ref.trim().toUpperCase();
    return this.admissionApplications.find(
      (a) => a.application_reference.toUpperCase() === cleanRef || a.phone.includes(cleanRef)
    );
  }
